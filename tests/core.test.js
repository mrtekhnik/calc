// Проверки ядра: node tests/core.test.js <путь к core.js>
const path = require('path');
const C = require(path.resolve(process.argv[2] || '../calc/core.js'));
let ok = 0, fail = 0;
function eq(name, got, exp) {
  const g = JSON.stringify(got), e = JSON.stringify(exp);
  if (g === e) ok++; else { fail++; console.log('✗', name, '\n   получено:', g, '\n   ожидалось:', e); }
}
const A = s => C.parseText(s);
const ev = s => { const r = C.evaluate(A(s)); return r && (r.err ? 'ERR:' + r.err : r.v); };

// приоритет, скобки, унарный минус, степень
eq('1+2*3', ev('1+2*3'), 7);
eq('(1+2)*3', ev('(1+2)*3'), 9);
eq('-2^2', ev('-2^2'), -4);
eq('2^3^2', ev('2^3^2'), 512);
eq('2^-1', ev('2^-1'), 0.5);
eq('5*-3', ev('5*-3'), -15);
eq('--3', ev('--3'), 3);
eq('незакрытая скобка', ev('2*(3+4'), 14);
eq('120*1,2+45*1,5', ev('120×1,2+45×1,5'), 211.5);
eq('80*1,2+70*1,1+75*1,2', ev('80*1,2+70*1,1+75*1,2'), 263);
eq('72/4', ev('72/4'), 18);
// точность
eq('0.1+0.2', ev('0.1+0.2'), 0.3);
eq('0.1*3', ev('0.1*3'), 0.3);
eq('1.1*1.1', ev('1.1*1.1'), 1.21);
eq('1/3*3', ev('1/3*3'), 1);
eq('большие целые', ev('123456789012*10'), 1234567890120);
// проценты (как в FlexCalc)
eq('100000×12,3%', ev('100000×12,3%'), 12300);
eq('10000×12,3%', ev('10000*12,3%'), 1230);
eq('23250−23%', ev('23250-23%'), 17902.5);
eq('100+10%', ev('100+10%'), 110);
eq('100+10%+10%', ev('100+10%+10%'), 121);
eq('200÷50%', ev('200/50%'), 400);
eq('10%', ev('10%'), 0.1);
eq('150000×0,155', ev('150000*0,155'), 23250);
// функции
const evA = atoms => { const r = C.evaluate(atoms); return r && (r.err ? 'ERR:' + r.err : r.v); };
eq('√16', evA(['√', '1', '6']), 4);
eq('√(9+7)', evA(['√', '(', '9', '+', '7', ')']), 4);
eq('2√9', evA(['2', '×', '√', '9']), 6);
eq('∛27', evA(['∛', '2', '7']), 3);
eq('3²', evA(['3', '²']), 9);
eq('2³', evA(['2', '³']), 8);
eq('5!', evA(['5', '!']), 120);
eq('ln e', evA(['ln', '(', 'e', ')']), 1);
eq('log 1000', evA(['log', '(', '1', '0', '0', '0', ')']), 3);
eq('lg2 8', evA(['lg2', '(', '8', ')']), 3);
eq('abs(-5)', evA(['abs', '(', '-', '5', ')']), 5);
eq('2π', evA(['2', '×', 'π']), 6.2831853071796);
// ошибки показываются в строке
eq('деление на ноль', ev('5/0'), 'ERR:Деление на ноль');
eq('5/(2-2)', ev('5/(2-2)'), 'ERR:Деление на ноль');
eq('√-4', evA(['√', '-', '4']), 'ERR:Корень из отрицательного числа');
eq('ln 0', evA(['ln', '(', '0', ')']), 'ERR:Логарифм числа ≤ 0');
eq('2.5!', evA(['2', '.', '5', '!']), 'ERR:x! — только для целых ≥ 0');
eq('1..2', evA(['1', '.', '.', '2']), 'ERR:Две запятые в числе');
eq('5+', ev('5+'), 'ERR:Не хватает числа');
eq('лишняя скобка', ev('5)'), 'ERR:Лишняя скобка');
eq('пустое', C.evaluate([]), null);
eq('переполнение', ev('10^400'), 'ERR:Слишком большое число');
eq('нет действия', evA(['(', '2', ')', '(', '3', ')']), 'ERR:Нет действия между числами');

// ссылки между строками
let lines = [
  {id: 'a', expr: A('150000*0,155')},
  {id: 'b', expr: [{r: 'a'}, '-', '2', '3', '%']},
  {id: 'c', expr: [{r: 'b'}, '÷', '5', '.', '5']},
  {id: 'd', expr: [{r: 'c'}, '+', '6', '8']},
];
let R = C.computeAll(lines);
eq('цепочка a', R.get('a').v, 23250);
eq('цепочка b', R.get('b').v, 17902.5);
eq('цепочка c', R.get('c').v, 3255);
eq('цепочка d', R.get('d').v, 3323);
lines[0].expr = A('100000*0,155'); // правка исходной строки — все зависимые пересчитываются
R = C.computeAll(lines);
eq('пересчёт d', R.get('d').v, 2238);
eq('зависимость d→a', C.dependsOn(lines, 'd', 'a'), true);
eq('нет зависимости a→d', C.dependsOn(lines, 'a', 'd'), false);
eq('сама на себя', C.dependsOn(lines, 'a', 'a'), true);
eq('прямые зависимые a', C.directDependents(lines, 'a').map(l => l.id), ['b']);
// цикл
const cyc = [{id: 'x', expr: [{r: 'y'}, '+', '1']}, {id: 'y', expr: [{r: 'x'}, '+', '1']}, {id: 'z', expr: [{r: 'x'}, '×', '2']}];
R = C.computeAll(cyc);
eq('цикл x', R.get('x').err, 'Цикл ссылок');
eq('цикл y', R.get('y').err, 'Цикл ссылок');
eq('цикл z', R.get('z').err, 'Цикл ссылок');
// ошибка в исходной строке не ломает остальные
const er = [{id: 'p', expr: A('1/0')}, {id: 'q', expr: [{r: 'p'}, '+', '1']}, {id: 'w', expr: A('2+2')}];
R = C.computeAll(er);
eq('ошибка зависимой', R.get('q').err, 'Ошибка в связанной строке');
eq('остальные считаются', R.get('w').v, 4);
// удалённая строка
const gone = [{id: 'p', expr: A('5'), del: 1}, {id: 'q', expr: [{r: 'p'}, '+', '1']}];
eq('ссылка на удалённую', C.computeAll(gone).get('q').err, 'Связанная строка удалена');
// заморозка ссылки при удалении
eq('freeze', C.freezeRef([{r: 'a'}, '+', '1'], 'a', 17902.5), ['1', '7', '9', '0', '2', '.', '5', '+', '1']);
eq('freeze отрицательное', C.freezeRef(['2', '×', {r: 'a'}], 'a', -3), ['2', '×', '(', '-', '3', ')']);
eq('freeze считается', C.evaluate(C.freezeRef(['2', '×', {r: 'a'}], 'a', -3)).v, -6);
eq('plain 1e-7', C.plain(1e-7), '0.0000001');
eq('plain 1.5e21', C.plain(1.5e21), '1500000000000000000000');

// форматирование
const G = C.GROUP;
eq('fmt 12300', C.fmt(12300), '12' + G + '300');
eq('fmt 17902.5', C.fmt(17902.5), '17' + G + '902,5');
eq('fmt 55/3', C.fmt(55 / 3), '18,3333');
eq('fmt 2/3', C.fmt(2 / 3), '0,6667');
eq('fmt 0', C.fmt(0), '0');
eq('fmt отрицательное', C.fmt(-1234.5), '−1' + G + '234,5');
eq('fmt малое', C.fmt(0.000123456), '0,0001235');
eq('fmt точка', C.fmt(1234.5, {sep: '.'}), '1' + G + '234.5');
eq('fmt без групп', C.fmt(1234567.25, {group: false}), '1234567,25');
eq('fmt dec=2', C.fmt(3.14159, {dec: 2}), '3,14');
eq('fmt dec=0', C.fmt(2.5, {dec: 0}), '3');
eq('fmt огромное', C.fmt(1.234e20), '1,234e20');
eq('fmt крошечное', C.fmt(1e-20), '1e-20');
eq('fmt 1.005 dec2', C.fmt(1.005, {dec: 2}), '1,01');
eq('fmtCopy', C.fmtCopy(-1234.5), '-1234,5');

// правила ввода
const S = (atoms, cur, sel) => ({atoms, cur: cur === undefined ? atoms.length : cur, sel: sel || null});
const typ = (st, ...keys) => keys.reduce((s, k) => C.insert(s, k), st);
const str = st => st.atoms.map(a => C.isRef(a) ? '[' + a.r + ']' : a).join('') + '|' + st.cur;
eq('ввод 12+3', str(typ(S([]), '1', '2', '+', '3')), '12+3|4');
eq('замена действия', str(typ(S([]), '5', '+', '×')), '5×|2');
eq('5×− унарный', str(typ(S([]), '5', '×', '-')), '5×-|3');
eq('5×−+ → 5+', str(typ(S([]), '5', '×', '-', '+')), '5+|2');
eq('ведущий ноль', str(typ(S([]), '0', '5')), '5|1');
eq('00 в начале', str(typ(S([]), '00')), '0|1');
eq('100', str(typ(S([]), '1', '00')), '100|3');
eq('запятая в начале', str(typ(S([]), '.')), '0.|2');
eq('вторая запятая игнор', str(typ(S([]), '1', '.', '5', '.')), '1.5|3');
eq('× перед скобкой', str(typ(S([]), '2', '(')), '2×(|3');
eq(') без открытой', str(typ(S([]), '2', ')')), '2|1');
eq('ln со скобкой', str(typ(S([]), 'ln')), 'ln(|2');
eq('ссылка после числа', str(typ(S([]), '6', '8', {r: 'a'})), '68×[a]|4');
eq('цифра после ссылки', str(typ(S([{r: 'a'}]), '5')), '[a]×5|3');
eq('+ в начале игнор', str(typ(S([]), '+')), '|0');
eq('− в начале', str(typ(S([]), '-', '5')), '-5|2');
eq('% после %', str(typ(S([]), '5', '%', '%')), '5%|2');
eq('% без числа', str(typ(S([]), '%')), '|0');
// правка внутри числа
eq('курсор в середине', str(C.insert(S(['1', '2', '3'], 1), '9')), '1923|2');
eq('замена выделенного числа', str(C.insert(S(['3', '2', '5', '5', '+', '6', '8'], 7, [5, 7]), '7')), '3255+7|6');
eq('замена числа ссылкой', str(C.insert(S(['3', '+', '6', '8'], 4, [2, 4]), {r: 'k'})), '3+[k]|3');
eq('замена действия по выделению', str(C.insert(S(['3', '+', '6'], 2, [1, 2]), '×')), '3×6|2');
eq('стереть', str(C.backspace(S(['1', '2', '3']))), '12|2');
eq('стереть ln(', str(C.backspace(S(['ln', '(']))), '|0');
eq('стереть выделение', str(C.backspace(S(['1', '2', '+', '3'], 2, [0, 2]))), '+3|0');
eq('удалить вперёд', str(C.delForward(S(['1', '2', '3'], 0))), '23|0');
eq('runAt', C.runAt(['1', '2', '+', '3', '.', '4'], 4), [3, 6]);
// вставка текста
eq('parseText', A('1 234,5 × 2').join(''), '1234.5×2');
eq('parseText точка и запятая', A('1,234.5').join(''), '1234.5');
eq('parseText со знаком =', A('2+2=4').join(''), '2+2');
// текст для копирования
eq('exprText', C.exprText([{r: 'a'}, '-', '2', '3', '%'], () => 23250), '23 250 − 23%');

// округление с шагом
const RA = (fn, x, step) => [fn, '(', ...C.parseText(x), ...(step ? [';', ...C.parseText(step)] : []), ')'];
eq('окр(2,675; 0,01)', evA(RA('rnd', '2,675', '0,01')), 2.68);
eq('окр(12,3)', evA(RA('rnd', '12,3')), 12);
eq('окр(-2,5)', evA(RA('rnd', '-2,5')), -3);
eq('вверх(12,1; 0,5)', evA(RA('rup', '12,1', '0,5')), 12.5);
eq('вниз(12,9; 0,5)', evA(RA('rdn', '12,9', '0,5')), 12.5);
eq('вверх(1234; 100)', evA(RA('rup', '1234', '100')), 1300);
eq('вниз(-1,2)', evA(RA('rdn', '-1,2')), -2);
eq('окр внутри выражения', evA(['2', '×', ...RA('rnd', '1,26', '0,1')]), 2.6);
eq('незакрытая окр(', evA(['rnd', '(', '3', '.', '7']), 4);
eq('окр без шага после ;', evA(['rnd', '(', '1', '2', '.', '6', ';']), 13);
eq('окр(…;) со скобкой', evA(['rnd', '(', '1', '2', '.', '6', ';', ')']), 13);
eq('шаг 0', evA(RA('rnd', '5', '0')), 'ERR:Шаг округления должен быть больше 0');
eq('; вне функции', evA(['(', '2', ';', '3', ')']), 'ERR:«;» — только внутри окр(…), вверх(…), вниз(…)');
eq('ввод ;', str(typ(S([]), 'rnd', '5', ';', '2')), 'rnd(5;2|5');
eq('; без скобки игнор', str(typ(S([]), '5', ';')), '5|1');
eq('exprText окр', C.exprText(RA('rnd', '2,675', '0,01'), () => 0), 'окр(2,675; 0,01)');
// подбор значения
const near = (n, g, e) => eq(n, g && Math.abs(g.x - e) < 1e-9 * Math.max(1, Math.abs(e)), true);
near('подбор линейный', C.solve(x => x * 0.155, 31000, 150000), 200000);
near('подбор квадрат', C.solve(x => x * x, 2, 1), Math.SQRT2);
near('подбор от нуля', C.solve(x => 3 * x + 5, 20, 0), 5);
near('подбор масса листа', C.solve(t => 1250 * 2500 * t * 7.85e-6, 98.125, 2), 4);
near('подбор с процентом', C.solve(x => x * (1 - 0.23), 17902.5, 1), 23250);
eq('подбор невозможен', C.solve(x => x * x, -1, 3), null);
near('подбор с ошибками вокруг', C.solve(x => { if (x <= 0) throw new Error('ln'); return Math.log(x); }, 2, 1), Math.exp(2));

console.log(`\nЯдро: пройдено ${ok}, ошибок ${fail}`);
process.exit(fail ? 1 : 0);
